// Возвращает sorted(values)[k] и помещает ответ в values[k].
// Слева значения <= ответа, справа >= ответа. Массив изменяется.
// T должен поддерживать копирование, обмен и согласованное сравнение <.
// Для вещественных типов NaN не допускается.
// Время O(n) в худшем случае, дополнительная память O(log n) на стек.
// Шаблон: T заменяется типом элементов (например, int, long long или double).
template <class T>
// Публичная функция: принимает изменяемый массив и индекс с нуля, возвращает найденный элемент типа T.
T select_kth(std::vector<T>& values, std::size_t k) {
    /*
     * Автор: Codex (OpenAI).
     * Принимает: изменяемый массив и ранг по контракту внутренней функции.
     * Возвращает: найденное значение; неверные аргументы вызывают исключение.
     */
    // Проверяем пустой массив до любых обращений к его элементам.
    if (values.empty()) {
        // Сообщаем ошибку аргумента исключением; выполнение функции прекращается.
        throw std::invalid_argument("values must not be empty");
    }
    // Допустимые индексы: 0..size()-1. size_t беззнаковый: отрицательный ввод проверяет вызывающий код.
    if (k >= values.size()) {
        // Сообщаем выход индекса за границы. Массив к этому моменту ещё не изменён.
        throw std::out_of_range("k must be in [0, values.size())");
    }
    // Запускаем выбор по всему массиву: начало 0, исключённый конец size().
    detail::select_range(values, 0, values.size(), k);
    // Возвращаем копию найденного значения; оно также остаётся на позиции k в исходном массиве.
    return values[k];
}
