// Все диапазоны полуоткрытые: [left, right). k — абсолютный индекс.
// Шаблон: T заменяется типом элементов (например, int, long long или double).
template <class T>
// Сортируем a[left:right] вставками. & передаёт исходный массив по ссылке; void — нет возвращаемого значения.
void insertion_sort(std::vector<T>& a, std::size_t left, std::size_t right) {
    /*
     * Автор: Codex (OpenAI).
     * Принимает: изменяемый массив и полуоткрытый диапазон [left,right).
     * Возвращает: ничего; сортирует малую группу вставками.
     */
    // Первый элемент уже образует отсортированный участок; по очереди добавляем к нему следующие.
    for (std::size_t i = left + 1; i < right; ++i) {
        // Сохраняем вставляемое значение: сдвиги ниже перезапишут его прежнее место. const запрещает менять копию.
        const T value = a[i];
        // j — текущая позиция свободного места, которое будем сдвигать влево.
        std::size_t j = i;
        // Пока слева есть элемент и он больше value, продолжаем сдвиг. && не вычисляет вторую часть, если первая ложна.
        while (j > left && value < a[j - 1]) {
            // Переносим больший элемент на одну позицию вправо, освобождая место для value.
            a[j] = a[j - 1];
            // Перемещаем свободное место влево. Проверка j > left выше защищает от выхода за границу.
            --j;
        }
        // Вставляем сохранённый элемент. Теперь участок [left, i + 1) отсортирован.
        a[j] = value;
    }
}

// [left, less) < pivot; [less, greater) == pivot;
// [greater, right) > pivot. Сам pivot хранится по значению.
// Шаблон: T заменяется типом элементов (например, int, long long или double).
template <class T>
// Объявляем разбиение; возвращаем пару индексов начала и конца блока равных.
std::pair<std::size_t, std::size_t> partition_three_way(
    // Работаем в исходном a на [left, right). pivot — копия числа, поэтому обмены элементов её не изменяют.
    std::vector<T>& a, std::size_t left, std::size_t right, const T pivot) {
    /*
     * Автор: Codex (OpenAI).
     * Принимает: массив, границы и копию опорного значения.
     * Возвращает: границы блока равных после трёхстороннего разбиения.
     */
    // Граница блока меньших: [left, less) содержит только значения < pivot.
    std::size_t less = left;
    // Индекс следующего непроверенного элемента. [less, current) уже содержит равные pivot.
    std::size_t current = left;
    // Начало блока больших: [greater, right) содержит > pivot. Изначально все блоки проверенных пусты.
    std::size_t greater = right;
    // Пока непроверенный участок [current, greater) не пуст, обрабатываем его первый элемент.
    while (current < greater) {
        // Случай 1: очередное число должно оказаться в блоке меньших.
        if (a[current] < pivot) {
            // Обмениваем a[less] и a[current], затем увеличиваем оба индекса. Постфиксный ++ использует старое значение.
            std::swap(a[less++], a[current++]);
            // Случай 2: очередное число больше опорного, его нужно перенести вправо.
        } else if (pivot < a[current]) {
            // Сначала уменьшаем greater (префиксный --), затем меняем элементы. current не сдвигаем: пришедшее число не проверено.
            std::swap(a[current], a[--greater]);
            // Пришедший справа элемент ещё не проверен.
            // Оставшийся случай: в разбиении это равенство pivot, в выборе диапазона — попадание k в блок равных.
        } else {
            // Случай 3: число эквивалентно pivot по сравнению <; включаем его в блок равных и идём дальше.
            ++current;
        }
    }
    // Возвращаем полуоткрытый блок равных [less, greater). Вне его слева строго меньшие, справа строго большие.
    return {less, greater};
}

// Шаблон: T заменяется типом элементов (например, int, long long или double).
template <class T>
// Внутренняя функция выбора на части массива; left включён в диапазон.
void select_range(std::vector<T>& a, std::size_t left,
                  // right не включён; k — абсолютный индекс в a. Предусловие: left <= k < right.
                  std::size_t right, std::size_t k) {
    /*
     * Автор: Codex (OpenAI).
     * Принимает: массив, рабочий диапазон и абсолютный нулевой индекс k.
     * Возвращает: ничего; устанавливает статистику на позиции k.
     */
    // Постоянный порог: диапазон из пяти или менее элементов сортируем напрямую.
    constexpr std::size_t small_threshold = 5;
    // Продолжаем, пока в рабочем диапазоне больше одного элемента. Длина равна right - left.
    while (right - left > 1) {
        // Базовый случай: диапазон достаточно мал для сортировки вставками.
        if (right - left <= small_threshold) {
            // Сортируем маленький диапазон; нужное число сразу оказывается на абсолютной позиции k.
            insertion_sort(a, left, right);
            // Завершаем текущий вызов: нужное значение уже стоит на позиции k.
            return;
        }

        // Счётчик собранных медиан; также задаёт следующую свободную позицию в их префиксе.
        std::size_t groups = 0;
        // Обходим группы слева направо. Шаг выполняется в конце тела через group_left = group_right.
        for (std::size_t group_left = left; group_left < right;) {
            // Вычисляем правую НЕ включённую границу текущей группы; выражение продолжается на следующей строке.
            const std::size_t group_right =
                // Берём максимум пять оставшихся элементов. Последняя группа может быть короче; за right не выходим.
                group_left + std::min<std::size_t>(5, right - group_left);
            // Сортируем только текущую группу, чтобы её центральный элемент стал медианой.
            insertion_sort(a, group_left, group_right);
            // Индекс медианы: начало плюс половина длины. Целочисленное / отбрасывает дробь; при чётной длине берём верхнюю середину.
            const std::size_t median = group_left + (group_right - group_left) / 2;
            // Обменом собираем медианы в начале рабочего диапазона. Исходные элементы не теряются, отдельный массив не нужен.
            std::swap(a[left + groups], a[median]);
            // Ещё одна медиана готова: увеличиваем длину префикса медиан.
            ++groups;
            // Следующая группа начинается сразу после текущей.
            group_left = group_right;
        }

        // Абсолютная позиция центральной медианы в префиксе [left, left + groups). Пока это индекс, а не готовое значение.
        const std::size_t median_of_medians = left + groups / 2;
        // Рекурсивно выбираем центральную медиану тем же BFPRT. Просто брать средний элемент неотсортированных медиан нельзя.
        select_range(a, left, left + groups, median_of_medians);
        // Теперь на рассчитанной позиции лежит медиана медиан. Копируем её как опорное значение.
        const T pivot = a[median_of_medians];
        // Разбиваем весь рабочий диапазон. auto выводит тип пары; first — начало блока равных, second — его конец.
        const auto bounds = partition_three_way(a, left, right, pivot);

        // Если искомая позиция левее блока равных, ответ среди меньших значений.
        if (k < bounds.first) {
            // Сужаем рабочий диапазон до левой части; следующая итерация while продолжит поиск.
            right = bounds.first;
            // Если позиция не раньше исключённой правой границы блока равных, ответ среди больших.
        } else if (k >= bounds.second) {
            // Оставляем правую часть. k не пересчитываем, поскольку индексы остаются абсолютными.
            left = bounds.second;
            // Оставшийся случай: в разбиении это равенство pivot, в выборе диапазона — попадание k в блок равных.
        } else {
            // Завершаем текущий вызов: нужное значение уже стоит на позиции k.
            return;
        }
    }
}
