// УЧЕБНОЕ ОБЪЯСНЕНИЕ: алгоритм BFPRT (медиана медиан).
// Цель: получить sorted(values)[k] без полной сортировки большого массива.
// k начинается с нуля: 0 — минимум, size()-1 — максимум. Повторы учитываются.
// Итог: values[k] содержит ответ, слева значения <= ответа, справа >= ответа.
//
// Порядок чтения: select_kth -> select_range -> insertion_sort / partition_three_way.
// Все диапазоны полуоткрытые: [left, right), длина right-left, right не включён.
// Пример [2,5): обрабатываются индексы 2, 3, 4. k всегда абсолютный индекс.
// Фигурные скобки открывают и закрывают тело функции, цикла или условия.
// Отступы показывают вложенность. Строки с // — комментарии, они не выполняются.
//
// ПОЧЕМУ ЭТО ПРАВИЛЬНО:
// Разбиение устанавливает порядок трёх блоков: меньшие, равные, большие.
// Позиция k определяет единственный блок, где может находиться ответ.
// При сужении диапазона отброшенные элементы уже лежат с нужной стороны.
// Если k попал в равные — ответ готов; если остался один элемент — тоже готов.
//
// ПОЧЕМУ O(n): медиана медиан выбирается среди примерно n/5 медиан групп.
// У каждой медианы полной группы есть ещё два значения не меньше неё
// и два не больше. Поэтому pivot отсекает постоянную долю элементов.
// Оставшаяся строгая сторона имеет размер не более 7n/10 + O(1).
// T(n) <= T(ceil(n/5)) + T(7n/10 + O(1)) + O(n) = O(n).
// Стек рекурсии занимает O(log n); дополнительных массивов алгоритм не создаёт.
// Эти оценки предполагают постоянную стоимость сравнения и копирования числа.

